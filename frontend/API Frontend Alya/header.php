<script>
document.addEventListener("DOMContentLoaded", function() {
    const token = localStorage.getItem('auth_token');
    if (!token) {
        // Redirect to login if token is missing
        window.location.href = 'login.php';
        return;
    }

    try {
        // Decode JWT-ready base64 token payload generated by auth_middleware
        const base64Url = token.split('.')[0];
        const base64 = base64Url.replace(/-/g, '+').replace(/_/g, '/');
        const jsonPayload = decodeURIComponent(atob(base64).split('').map(function(c) {
            return '%' + ('00' + c.charCodeAt(0).toString(16)).slice(-2);
        }).join(''));
        
        const user = JSON.parse(jsonPayload);
        const role = (user.role || 'customer').toLowerCase();
        const fullName = user.full_name || 'User';

        // Update Header UI
        document.getElementById('header-user-name').innerText = fullName;
        document.getElementById('header-user-role').innerText = role.charAt(0).toUpperCase() + role.slice(1);
        document.getElementById('user-avatar-initial').innerText = fullName.charAt(0).toUpperCase();
        document.getElementById('portal-badge-text').innerText = (role.charAt(0).toUpperCase() + role.slice(1)) + ' Portal';

        // Update Brand Link Destination based on Role
        let dashFile = 'dashboard_customer.php';
        if (role === 'organiser') dashFile = 'dashboard_organiser.php';
        if (role === 'admin') dashFile = 'dashboard_admin.php';
        document.getElementById('brand-logo-link').href = dashFile;

        // Update Sidebar Navigation based on Role
        const navContainer = document.getElementById('sidebar-nav-container');
        const active = "<?= $activePage ?>";

        if (role === 'customer') {
            navContainer.innerHTML = `
                <a href="dashboard_customer.php" class="nav-item ${active == 'dashboard_customer' ? 'active' : ''}">
                    <i class="fa-solid fa-chart-pie nav-icon"></i><span>Customer Dashboard</span>
                </a>
                <a href="events.php" class="nav-item ${active == 'events' ? 'active' : ''}">
                    <i class="fa-solid fa-calendar-days nav-icon"></i><span>Events & Tickets</span>
                </a>
                <a href="bookings.php" class="nav-item ${active == 'bookings' ? 'active' : ''}">
                    <i class="fa-solid fa-ticket-simple nav-icon"></i><span>My Bookings</span>
                </a>
            `;
        } else if (role === 'organiser') {
            navContainer.innerHTML = `
                <a href="dashboard_organiser.php" class="nav-item ${active == 'dashboard_organiser' ? 'active' : ''}">
                    <i class="fa-solid fa-chart-pie nav-icon"></i><span>Organiser Dashboard</span>
                </a>
                <a href="manage_events.php" class="nav-item ${active == 'manage_events' ? 'active' : ''}">
                    <i class="fa-solid fa-pen-to-square nav-icon"></i><span>Manage Events</span>
                </a>
            `;
        } else {
            navContainer.innerHTML = `
                <a href="dashboard_admin.php" class="nav-item ${active == 'dashboard_admin' ? 'active' : ''}">
                    <i class="fa-solid fa-chart-pie nav-icon"></i><span>Admin Dashboard</span>
                </a>
                <a href="users.php" class="nav-item ${active == 'users' ? 'active' : ''}">
                    <i class="fa-solid fa-users-gear nav-icon"></i><span>User Accounts</span>
                </a>
                <a href="manage_events.php" class="nav-item ${active == 'manage_events' ? 'active' : ''}">
                    <i class="fa-solid fa-pen-to-square nav-icon"></i><span>Manage Events</span>
                </a>
            `;
        }

        // Dynamically update the Venues link for Administrators
        const venuesLink = document.getElementById('venues-sidebar-link');
        if (venuesLink) {
            if (role === 'admin') {
                venuesLink.href = 'venues_admin.php';
                venuesLink.querySelector('span').innerText = 'Manage Venues';
            } else {
                venuesLink.href = 'venues.php';
                venuesLink.querySelector('span').innerText = 'Venues Directory';
            }
        }
    } catch (e) {
        console.error('Error parsing auth token:', e);
        localStorage.removeItem('auth_token');
        window.location.href = 'login.php';
    }
});
</script>